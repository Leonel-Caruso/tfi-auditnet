-- =====================================================================
-- AuditNet · management-service · V6 — Correo y recuperación de contraseña
-- ---------------------------------------------------------------------
-- * correos_salientes: bandeja de salida común. Los dos servicios
--   guardan el aviso en la misma transacción que el evento (tipo y datos
--   en JSON); management-service arma el mensaje y lo envía después,
--   con reintentos. Si el proveedor no responde, el aviso no se pierde.
-- * usuarios.aviso_*: preferencias de cada usuario (alertas críticas,
--   vencimientos y resumen mensual). Los correos de la cuenta
--   (recuperación, alta) se envían siempre.
-- * recuperaciones_contrasena: enlaces de un solo uso. Se guarda solo
--   el hash SHA-256 del token, nunca el token.
-- =====================================================================

CREATE TABLE correos_salientes (
    id_correo           bigint GENERATED BY DEFAULT AS IDENTITY,
    origen              varchar(30)                 NOT NULL,
    tipo                varchar(40)                 NOT NULL,
    id_organizacion     bigint,
    destinatario        varchar(160)                NOT NULL,
    nombre_destinatario varchar(140),
    datos               text                        NOT NULL,
    estado              varchar(20)                 NOT NULL,
    intentos            integer                     NOT NULL DEFAULT 0,
    proximo_intento     timestamp(6) with time zone NOT NULL,
    creado_en           timestamp(6) with time zone NOT NULL,
    enviado_en          timestamp(6) with time zone,
    ultimo_error        varchar(500),
    id_envio            varchar(100),
    CONSTRAINT correos_salientes_pkey PRIMARY KEY (id_correo),
    CONSTRAINT ck_correos_salientes_estado CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO')),
    CONSTRAINT ck_correos_salientes_intentos CHECK (intentos >= 0),
    CONSTRAINT fk_correos_salientes_organizacion
        FOREIGN KEY (id_organizacion) REFERENCES organizaciones_cliente (id_organizacion)
);

CREATE INDEX ix_correos_salientes_pendientes ON correos_salientes (proximo_intento) WHERE estado = 'PENDIENTE';
CREATE INDEX ix_correos_salientes_creado ON correos_salientes (creado_en DESC);

ALTER TABLE usuarios ADD COLUMN aviso_alertas boolean NOT NULL DEFAULT true;
ALTER TABLE usuarios ADD COLUMN aviso_vencimientos boolean NOT NULL DEFAULT true;
ALTER TABLE usuarios ADD COLUMN aviso_resumen boolean NOT NULL DEFAULT true;

CREATE TABLE recuperaciones_contrasena (
    id_recuperacion bigint GENERATED BY DEFAULT AS IDENTITY,
    id_usuario      bigint                      NOT NULL,
    token_hash      varchar(64)                 NOT NULL,
    creada_en       timestamp(6) with time zone NOT NULL,
    vence_en        timestamp(6) with time zone NOT NULL,
    usada_en        timestamp(6) with time zone,
    CONSTRAINT recuperaciones_contrasena_pkey PRIMARY KEY (id_recuperacion),
    CONSTRAINT uk_recuperacion_token UNIQUE (token_hash),
    CONSTRAINT fk_recuperaciones_contrasena_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario)
);

CREATE INDEX ix_recuperaciones_contrasena_usuario ON recuperaciones_contrasena (id_usuario, creada_en DESC);
