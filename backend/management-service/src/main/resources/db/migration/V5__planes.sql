CREATE TABLE solicitudes_cambio_plan (
    id_solicitud       bigint GENERATED BY DEFAULT AS IDENTITY,
    id_organizacion    bigint                      NOT NULL,
    id_plan_actual     bigint                      NOT NULL,
    id_plan_solicitado bigint                      NOT NULL,
    modalidad          varchar(10)                 NOT NULL,
    estado             varchar(20)                 NOT NULL,
    comentario         varchar(500),
    solicitado_por     varchar(100)                NOT NULL,
    fecha_solicitud    timestamp(6) with time zone NOT NULL,
    resuelto_por       varchar(100),
    fecha_resolucion   timestamp(6) with time zone,
    respuesta          varchar(500),
    CONSTRAINT solicitudes_cambio_plan_pkey PRIMARY KEY (id_solicitud),
    CONSTRAINT ck_solicitudes_cambio_plan_modalidad CHECK (modalidad IN ('MENSUAL', 'ANUAL')),
    CONSTRAINT ck_solicitudes_cambio_plan_estado
        CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'CANCELADA')),
    CONSTRAINT fk_solicitudes_cambio_plan_organizacion
        FOREIGN KEY (id_organizacion) REFERENCES organizaciones_cliente (id_organizacion),
    CONSTRAINT fk_solicitudes_cambio_plan_actual FOREIGN KEY (id_plan_actual) REFERENCES planes (id_plan),
    CONSTRAINT fk_solicitudes_cambio_plan_solicitado FOREIGN KEY (id_plan_solicitado) REFERENCES planes (id_plan)
);

CREATE UNIQUE INDEX uk_solicitud_plan_pendiente
    ON solicitudes_cambio_plan (id_organizacion) WHERE estado = 'PENDIENTE';
CREATE INDEX ix_solicitudes_cambio_plan_estado ON solicitudes_cambio_plan (estado, fecha_solicitud);
