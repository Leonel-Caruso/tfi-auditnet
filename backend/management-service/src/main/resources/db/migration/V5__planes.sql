-- AuditNet · management-service · V5 — Planes comerciales
-- ---------------------------------------------------------------------
-- * planes: catálogo de la carpeta (Tabla 20 y Tabla 32). Los límites
--   son de dispositivos y usuarios activos; un límite nulo indica un
--   plan a medida (Empresa). El precio es de referencia y lo edita el
--   administrador del sistema (se ajusta cada año, Tabla 33).
-- * organizaciones_cliente: plan asignado, inicio, vencimiento (piloto)
--   y límites acordados (plan a medida). Las organizaciones existentes
--   quedan en el plan Inicial.
-- * solicitudes_cambio_plan: pedidos de cambio de plan. Como mucho una
--   pendiente por organización.
-- =====================================================================

CREATE TABLE planes (
    id_plan            bigint GENERATED BY DEFAULT AS IDENTITY,
    codigo             varchar(30)    NOT NULL,
    nombre             varchar(80)    NOT NULL,
    max_dispositivos   integer,
    max_usuarios       integer,
    dias_vigencia      integer,
    precio_mensual_usd numeric(10, 2),
    condiciones        varchar(400),
    orden              integer        NOT NULL,
    CONSTRAINT planes_pkey PRIMARY KEY (id_plan),
    CONSTRAINT uk_plan_codigo UNIQUE (codigo),
    CONSTRAINT ck_planes_limites
        CHECK ((max_dispositivos IS NULL OR max_dispositivos > 0) AND (max_usuarios IS NULL OR max_usuarios > 0)),
    CONSTRAINT ck_planes_vigencia CHECK (dias_vigencia IS NULL OR dias_vigencia > 0),
    CONSTRAINT ck_planes_precio CHECK (precio_mensual_usd IS NULL OR precio_mensual_usd >= 0)
);

