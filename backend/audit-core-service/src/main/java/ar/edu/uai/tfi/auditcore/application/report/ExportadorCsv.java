package ar.edu.uai.tfi.auditcore.application.report;

import ar.edu.uai.tfi.auditcore.domain.model.ContenidoReporte.AuditoriaIncluida;
import ar.edu.uai.tfi.auditcore.domain.model.ContenidoReporte.HallazgoIncluido;
import ar.edu.uai.tfi.auditcore.domain.model.ReporteAuditoria;

import java.time.Instant;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Descarga del reporte en CSV (GET /api/reports/{id}/download), para abrir con Excel.
 *
 * <ul>
 *   <li>Una fila por hallazgo; las auditorías sin hallazgos incluidos van en una fila con el resultado.</li>
 *   <li>BOM UTF-8 y el separador que usa Excel en cada idioma (";" en español y portugués, "," en inglés), para que
 *   lo abra en columnas y con los acentos bien.</li>
 *   <li>Celdas que empiezan con = + - @ se anteponen con ' para que Excel no las tome como fórmulas.</li>
 *   <li>El que se guarda en el repositorio de archivos es el de español. En inglés y portugués cambian los
 *   encabezados y los códigos (severidad, estado, resultado); los datos cargados quedan como se registraron.</li>
 * </ul>
 */
public final class ExportadorCsv {

    /** Encabezados, separador y nombres de los códigos de cada idioma. */
    private enum Formato {
        ES(";", "reporte", List.of("Reporte", "Generado", "Generado por", "Auditoría", "Fecha auditoría", "Ejecutada por",
                "Dispositivo", "Criticidad", "Baseline", "Versión baseline", "Configuración", "Reglas cumplidas",
                "Reglas evaluadas", "Resultado auditoría", "Hallazgo", "Regla", "Nombre regla", "Severidad", "Impacto",
                "Estado hallazgo", "Evidencia", "Recomendación", "Detectado"), Map.of()),
        EN(",", "report", List.of("Report", "Generated", "Generated by", "Audit", "Audit date", "Run by",
                "Device", "Criticality", "Baseline", "Baseline version", "Configuration", "Rules met",
                "Rules evaluated", "Audit result", "Finding", "Rule", "Rule name", "Severity", "Impact",
                "Finding status", "Evidence", "Recommendation", "Detected"), Map.ofEntries(
                Map.entry("CRITICA", "CRITICAL"), Map.entry("ALTA", "HIGH"), Map.entry("MEDIA", "MEDIUM"),
                Map.entry("BAJA", "LOW"), Map.entry("CUMPLE", "COMPLIANT"), Map.entry("CON_HALLAZGOS", "WITH_FINDINGS"),
                Map.entry("ABIERTO", "OPEN"), Map.entry("EN_REVISION", "IN_REVIEW"), Map.entry("RESUELTO", "RESOLVED"),
                Map.entry("ACEPTADO", "ACCEPTED"))),
        PT(";", "relatorio", List.of("Relatório", "Gerado", "Gerado por", "Auditoria", "Data da auditoria", "Executada por",
                "Dispositivo", "Criticidade", "Baseline", "Versão da baseline", "Configuração", "Regras cumpridas",
                "Regras avaliadas", "Resultado da auditoria", "Achado", "Regra", "Nome da regra", "Severidade", "Impacto",
                "Estado do achado", "Evidência", "Recomendação", "Detectado"), Map.ofEntries(
                Map.entry("CRITICA", "CRÍTICA"), Map.entry("MEDIA", "MÉDIA"), Map.entry("BAJA", "BAIXA"),
                Map.entry("CUMPLE", "CONFORME"), Map.entry("CON_HALLAZGOS", "COM_ACHADOS"), Map.entry("ABIERTO", "ABERTO"),
                Map.entry("EN_REVISION", "EM_REVISÃO"), Map.entry("RESUELTO", "RESOLVIDO"), Map.entry("ACEPTADO", "ACEITO")));

        private final String separador;
        private final String archivo;
        private final List<String> encabezados;
        private final Map<String, String> codigos;

        Formato(String separador, String archivo, List<String> encabezados, Map<String, String> codigos) {
            this.separador = separador;
            this.archivo = archivo;
            this.encabezados = encabezados;
            this.codigos = codigos;
        }

        static Formato de(String idioma) {
            return valueOf(IdiomaReporte.de(idioma).name());
        }

        String codigo(String valor) {
            return valor == null ? "" : codigos.getOrDefault(valor, valor);
        }
    }

    private static final DateTimeFormatter FECHA = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm")
            .withZone(ReporteService.ZONA);

    private ExportadorCsv() {
    }

    /** El CSV en español: el que se guarda en el repositorio de archivos. */
    public static String exportar(ReporteAuditoria reporte) {
        return exportar(reporte, "es");
    }

    /** @param idioma es, en o pt (también acepta un encabezado Accept-Language); otro valor, español */
    public static String exportar(ReporteAuditoria reporte, String idioma) {
        Formato formato = Formato.de(idioma);
        StringBuilder csv = new StringBuilder("\uFEFF");
        linea(csv, formato, formato.encabezados);

        Map<Long, List<HallazgoIncluido>> porAuditoria = reporte.contenido().hallazgos().stream()
                .collect(Collectors.groupingBy(HallazgoIncluido::auditoriaId));
        for (AuditoriaIncluida auditoria : reporte.contenido().auditorias()) {
            List<String> base = List.of(
                    codigo("REP", reporte.id()),
                    fecha(reporte.fechaGeneracion()),
                    texto(reporte.generadoPor()),
                    codigo("AUD", auditoria.id()),
                    fecha(auditoria.fechaEjecucion()),
                    texto(auditoria.ejecutadoPor()),
                    texto(auditoria.dispositivoIdentificador()),
                    formato.codigo(auditoria.criticidadDispositivo()),
                    texto(auditoria.baselineNombre()),
                    auditoria.baselineVersion() == null ? "" : "v" + auditoria.baselineVersion(),
                    codigo("CFG", auditoria.configuracionId()),
                    String.valueOf(auditoria.reglasCumplidas()),
                    String.valueOf(auditoria.totalReglas()),
                    formato.codigo(auditoria.resultado()));
            List<HallazgoIncluido> hallazgos = porAuditoria.getOrDefault(auditoria.id(), List.of());
            if (hallazgos.isEmpty()) {
                linea(csv, formato, concatenar(base, List.of("", "", "", "", "", "", "", "", "")));
                continue;
            }
            for (HallazgoIncluido hallazgo : hallazgos) {
                linea(csv, formato, concatenar(base, List.of(
                        codigo("FND", hallazgo.id()),
                        texto(hallazgo.codigoRegla()),
                        texto(hallazgo.nombreRegla()),
                        formato.codigo(hallazgo.severidad()),
                        texto(hallazgo.impacto()),
                        formato.codigo(hallazgo.estado()),
                        texto(hallazgo.evidencia()),
                        texto(hallazgo.recomendacion()),
                        fecha(hallazgo.fechaDeteccion()))));
            }
        }
        return csv.toString();
    }

    /** El que se guarda en el repositorio es el de español: solo ese se puede entregar verificado. */
    public static boolean esIdiomaGuardado(String idioma) {
        return Formato.de(idioma) == Formato.ES;
    }

    /** Nombre del archivo para descargar: reporte-REP-001.csv, report-REP-001.csv o relatorio-REP-001.csv. */
    public static String nombreArchivo(Long id, String idioma) {
        return Formato.de(idioma).archivo + "-" + codigo("REP", id) + ".csv";
    }

    static String celda(String valor) {
        return celda(valor, Formato.ES.separador);
    }

    /** Escapa una celda: comillas si tiene separador, comillas o saltos de línea; neutraliza fórmulas. */
    private static String celda(String valor, String separador) {
        String limpio = valor == null ? "" : valor;
        if (!limpio.isEmpty() && "=+-@\t\r".indexOf(limpio.charAt(0)) >= 0) {
            limpio = "'" + limpio;
        }
        if (limpio.contains(separador) || limpio.contains("\"") || limpio.contains("\n") || limpio.contains("\r")) {
            limpio = "\"" + limpio.replace("\"", "\"\"") + "\"";
        }
        return limpio;
    }

    private static void linea(StringBuilder csv, Formato formato, List<String> celdas) {
        csv.append(celdas.stream()
                .map(celda -> celda(celda, formato.separador))
                .collect(Collectors.joining(formato.separador))).append("\r\n");
    }

    private static List<String> concatenar(List<String> a, List<String> b) {
        return java.util.stream.Stream.concat(a.stream(), b.stream()).toList();
    }

    private static String codigo(String prefijo, Long id) {
        return id == null ? "" : String.format("%s-%03d", prefijo, id);
    }

    private static String fecha(Instant instante) {
        return instante == null ? "" : FECHA.format(instante);
    }

    private static String texto(String valor) {
        return valor == null ? "" : valor;
    }
}
