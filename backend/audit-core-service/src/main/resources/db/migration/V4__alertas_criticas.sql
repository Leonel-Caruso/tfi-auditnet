-- =====================================================================
-- AuditNet · audit-core-service · V4 — Alertas críticas (Bloque 5.1)
-- ---------------------------------------------------------------------
-- CU-006-002: alertas internas generadas a partir de hallazgos de
-- severidad CRITICA o ALTA. Cada alerta:
--   * nace de un hallazgo registrado y conserva la auditoría de origen;
--   * se atiende (EN_ATENCION, derivada a un perfil técnico);
--   * se cierra cuando el hallazgo se resuelve o se acepta el riesgo, y
--     se reactiva si el hallazgo se reabre;
--   * no se borra nunca (evidencia histórica, regla 5).
-- No hay notificaciones externas (regla 6).
-- =====================================================================

CREATE TABLE alertas_criticas (
    id_alerta        bigint GENERATED BY DEFAULT AS IDENTITY,
    id_hallazgo      bigint                      NOT NULL,
    id_auditoria     bigint                      NOT NULL,
    id_dispositivo   bigint                      NOT NULL,
    id_organizacion  bigint                      NOT NULL,
    severidad        varchar(20)                 NOT NULL,
    estado           varchar(20)                 NOT NULL,
    fecha_generacion timestamp(6) with time zone NOT NULL,
    perfil_asignado  varchar(40),
    comentario       varchar(1000),
    fecha_estado     timestamp(6) with time zone,
    usuario_estado   varchar(120),
    CONSTRAINT alertas_criticas_pkey PRIMARY KEY (id_alerta),
    CONSTRAINT uk_alertas_criticas_hallazgo UNIQUE (id_hallazgo),
    CONSTRAINT ck_alertas_criticas_severidad CHECK (severidad IN ('ALTA', 'CRITICA')),
    CONSTRAINT ck_alertas_criticas_estado CHECK (estado IN ('ACTIVA', 'EN_ATENCION', 'CERRADA')),
    CONSTRAINT ck_alertas_criticas_perfil
        CHECK (perfil_asignado IS NULL OR perfil_asignado IN ('ANALISTA_RED', 'AUDITOR_TECNICO')),
    CONSTRAINT fk_alertas_criticas_hallazgo
        FOREIGN KEY (id_hallazgo) REFERENCES hallazgos_auditoria (id_hallazgo),
    CONSTRAINT fk_alertas_criticas_auditoria
        FOREIGN KEY (id_auditoria) REFERENCES auditorias_configuracion (id_auditoria),
    CONSTRAINT fk_alertas_criticas_dispositivo
        FOREIGN KEY (id_dispositivo) REFERENCES dispositivos_red (id_dispositivo),
    CONSTRAINT fk_alertas_criticas_organizacion
        FOREIGN KEY (id_organizacion) REFERENCES organizaciones_cliente (id_organizacion)
);

CREATE INDEX ix_alertas_criticas_organizacion_estado ON alertas_criticas (id_organizacion, estado);
CREATE INDEX ix_alertas_criticas_dispositivo ON alertas_criticas (id_dispositivo);

-- Las alertas cambian de estado, pero no se borran.
CREATE FUNCTION fn_alertas_criticas_sin_borrado() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'alertas_criticas no admite %: las alertas se conservan como evidencia', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_alertas_criticas_sin_borrado
    BEFORE DELETE ON alertas_criticas
    FOR EACH ROW EXECUTE FUNCTION fn_alertas_criticas_sin_borrado();

CREATE TRIGGER tr_alertas_criticas_sin_truncate
    BEFORE TRUNCATE ON alertas_criticas
    FOR EACH STATEMENT EXECUTE FUNCTION fn_alertas_criticas_sin_borrado();

-- Alertas de los hallazgos CRITICA o ALTA que ya existían: activas si el hallazgo sigue pendiente,
-- cerradas (con la fecha y el usuario del cierre del hallazgo) si ya se resolvió o se aceptó.
INSERT INTO alertas_criticas (id_hallazgo, id_auditoria, id_dispositivo, id_organizacion, severidad, estado,
                              fecha_generacion, comentario, fecha_estado, usuario_estado)
SELECT h.id_hallazgo,
       h.id_auditoria,
       h.id_dispositivo,
       h.id_organizacion,
       h.severidad,
       CASE WHEN h.estado IN ('RESUELTO', 'ACEPTADO') THEN 'CERRADA' ELSE 'ACTIVA' END,
       h.fecha_deteccion,
       CASE WHEN h.estado IN ('RESUELTO', 'ACEPTADO') THEN 'Hallazgo ' || h.estado || ' antes de crear las alertas (V4)' END,
       CASE WHEN h.estado IN ('RESUELTO', 'ACEPTADO') THEN h.fecha_estado END,
       CASE WHEN h.estado IN ('RESUELTO', 'ACEPTADO') THEN h.usuario_estado END
FROM hallazgos_auditoria h
WHERE h.severidad IN ('ALTA', 'CRITICA')
ORDER BY h.id_hallazgo;
