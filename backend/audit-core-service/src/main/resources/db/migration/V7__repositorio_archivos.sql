-- =====================================================================
-- AuditNet · audit-core-service · V7 — Repositorio de archivos (Bloque 7)
-- ---------------------------------------------------------------------
-- Diagrama de despliegue (10.5.9): las configuraciones importadas y los
-- reportes generados se guardan en un repositorio seguro de archivos
-- (Azure Blob Storage, contenedor privado). Esta tabla es el catálogo:
-- qué archivo corresponde a cada configuración, reporte o respaldo, su
-- tamaño y su hash SHA-256 para comprobar que no fue alterado (RNF-012).
-- Es de solo inserción, igual que las bitácoras.
-- =====================================================================

CREATE TABLE archivos_repositorio (
    id_archivo      bigint GENERATED BY DEFAULT AS IDENTITY,
    tipo            varchar(20)                 NOT NULL,
    id_entidad      bigint,
    id_organizacion bigint,
    ruta            varchar(400)                NOT NULL,
    nombre          varchar(200)                NOT NULL,
    tipo_contenido  varchar(100)                NOT NULL,
    tamanio_bytes   bigint                      NOT NULL,
    sha256          varchar(64)                 NOT NULL,
    fecha           timestamp(6) with time zone NOT NULL,
    usuario         varchar(120)                NOT NULL,
    detalle         varchar(500),
    CONSTRAINT archivos_repositorio_pkey PRIMARY KEY (id_archivo),
    CONSTRAINT uk_archivos_repositorio_ruta UNIQUE (ruta),
    CONSTRAINT ck_archivos_repositorio_tipo CHECK (tipo IN ('CONFIGURACION', 'REPORTE', 'RESPALDO')),
    CONSTRAINT ck_archivos_repositorio_tamanio CHECK (tamanio_bytes >= 0),
    CONSTRAINT ck_archivos_repositorio_sha256 CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_archivos_repositorio_entidad CHECK ((tipo = 'RESPALDO') = (id_entidad IS NULL)),
    CONSTRAINT fk_archivos_repositorio_organizacion
        FOREIGN KEY (id_organizacion) REFERENCES organizaciones_cliente (id_organizacion)
);

-- Un único archivo por configuración y por reporte.
CREATE UNIQUE INDEX uk_archivos_repositorio_entidad ON archivos_repositorio (tipo, id_entidad)
    WHERE id_entidad IS NOT NULL;
CREATE INDEX ix_archivos_repositorio_tipo_fecha ON archivos_repositorio (tipo, fecha DESC);

CREATE FUNCTION fn_archivos_repositorio_solo_insercion() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% es de solo inserción: no se permite %', TG_TABLE_NAME, TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_archivos_repositorio_sin_cambios
    BEFORE UPDATE OR DELETE ON archivos_repositorio
    FOR EACH ROW EXECUTE FUNCTION fn_archivos_repositorio_solo_insercion();

CREATE TRIGGER tr_archivos_repositorio_sin_truncate
    BEFORE TRUNCATE ON archivos_repositorio
    FOR EACH STATEMENT EXECUTE FUNCTION fn_archivos_repositorio_solo_insercion();
