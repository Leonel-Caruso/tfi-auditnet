-- =====================================================================
-- AuditNet · audit-core-service · V5 — Reportes de auditoría (Bloque 5.2)
-- ---------------------------------------------------------------------
-- CU-006-001: el reporte se guarda como una foto fija (criterios y
-- contenido en JSON), con la fecha y el usuario que lo generó. No se
-- modifica ni se borra: es evidencia para la auditoría técnica.
-- reportes_auditoria_auditorias conserva la referencia a cada auditoría
-- usada como fuente (regla 4).
-- =====================================================================

CREATE TABLE reportes_auditoria (
    id_reporte       bigint GENERATED BY DEFAULT AS IDENTITY,
    id_organizacion  bigint,
    titulo           varchar(160)                NOT NULL,
    criterios        text                        NOT NULL,
    contenido        text                        NOT NULL,
    total_auditorias integer                     NOT NULL,
    total_hallazgos  integer                     NOT NULL,
    generado_por     varchar(120)                NOT NULL,
    fecha_generacion timestamp(6) with time zone NOT NULL,
    CONSTRAINT reportes_auditoria_pkey PRIMARY KEY (id_reporte),
    CONSTRAINT ck_reportes_auditoria_totales CHECK (total_auditorias > 0 AND total_hallazgos >= 0),
    CONSTRAINT fk_reportes_auditoria_organizacion
        FOREIGN KEY (id_organizacion) REFERENCES organizaciones_cliente (id_organizacion)
);

-- id_organizacion NULL = reporte del administrador sobre todas las organizaciones.
CREATE INDEX ix_reportes_auditoria_organizacion ON reportes_auditoria (id_organizacion, fecha_generacion DESC);

CREATE TABLE reportes_auditoria_auditorias (
    id_reporte   bigint NOT NULL,
    id_auditoria bigint NOT NULL,
    CONSTRAINT reportes_auditoria_auditorias_pkey PRIMARY KEY (id_reporte, id_auditoria),
    CONSTRAINT fk_reportes_auditoria_auditorias_reporte
        FOREIGN KEY (id_reporte) REFERENCES reportes_auditoria (id_reporte),
    CONSTRAINT fk_reportes_auditoria_auditorias_auditoria
        FOREIGN KEY (id_auditoria) REFERENCES auditorias_configuracion (id_auditoria)
);

CREATE INDEX ix_reportes_auditoria_auditorias_auditoria ON reportes_auditoria_auditorias (id_auditoria);

-- Los reportes son de solo inserción.
CREATE FUNCTION fn_reportes_auditoria_solo_insercion() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% es de solo inserción: no se permite %', TG_TABLE_NAME, TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_reportes_auditoria_sin_cambios
    BEFORE UPDATE OR DELETE ON reportes_auditoria
    FOR EACH ROW EXECUTE FUNCTION fn_reportes_auditoria_solo_insercion();

CREATE TRIGGER tr_reportes_auditoria_sin_truncate
    BEFORE TRUNCATE ON reportes_auditoria
    FOR EACH STATEMENT EXECUTE FUNCTION fn_reportes_auditoria_solo_insercion();

CREATE TRIGGER tr_reportes_auditoria_auditorias_sin_cambios
    BEFORE UPDATE OR DELETE ON reportes_auditoria_auditorias
    FOR EACH ROW EXECUTE FUNCTION fn_reportes_auditoria_solo_insercion();

CREATE TRIGGER tr_reportes_auditoria_auditorias_sin_truncate
    BEFORE TRUNCATE ON reportes_auditoria_auditorias
    FOR EACH STATEMENT EXECUTE FUNCTION fn_reportes_auditoria_solo_insercion();
